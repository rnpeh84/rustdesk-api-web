// 수동 미리보기의 실제 로그인과 암호화 연결을 검증한다. 운영 서버에는 접근하지 않는다.
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { join } from 'node:path'
const require=createRequire(import.meta.url)
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright')
const previewRoot=new URL('../../runtime/web-terminal-preview/',import.meta.url)
const ready=JSON.parse(await readFile(new URL('ready.json',previewRoot),'utf8'))
const access=await readFile(new URL('계정정보.txt',previewRoot),'utf8')
const password=access.match(/^비밀번호: (.+)$/m)[1].trim()
const browser=await chromium.launch({headless:true,channel:'chrome'})
const context=await browser.newContext({locale:'ko-KR',acceptDownloads:true})
const page=await context.newPage(),errors=[]
const missing=[]
page.on('response',response=>{if(response.status()===404)missing.push(new URL(response.url()).pathname)})
page.setDefaultTimeout(15000)
page.on('pageerror',error=>errors.push(error.message))
await context.addInitScript(()=>localStorage.setItem('lang','ko'))
try{
  await page.goto(ready.origin+'/#/my/peer')
  await page.locator('.login-form input[type="username"]').fill('local-tester')
  await page.locator('.login-form input[type="password"]').fill(password)
  const loggingIn=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/admin/login')
  await page.getByRole('button',{name:'로그인',exact:true}).click()
  const loginReply=await loggingIn
  const loginBody=await loginReply.json()
  assert.equal(loginBody.code,0,`로그인 실패: HTTP ${loginReply.status()}, code ${loginBody.code}, ${loginBody.message||''}`)
  await page.getByRole('button',{name:'터미널 접속 123456789',exact:true}).waitFor()
  assert.equal(await page.locator('.notification-center').count(),0,'로그인 후 터미널 밖에 고정 알림창이 생겼습니다.')
  await page.getByRole('button',{name:'상세 정보 123456789',exact:true}).click()
  const details=page.locator('.device-detail-drawer')
  await page.waitForFunction(()=>/fixture CPU|8 CPU/.test(document.querySelector('.device-detail-drawer')?.textContent||''))
  await details.getByText('16 GB',{exact:true}).waitFor()
  await details.locator('.el-drawer__close-btn').click()
  await details.waitFor({state:'hidden'})
  await page.getByRole('button',{name:'터미널 접속 123456789',exact:true}).click()
  const terminal=page.getByRole('dialog',{name:'ID : 123456789',exact:true})
  await terminal.getByText('접속 중',{exact:true}).waitFor()
  assert.equal(await terminal.locator('.notification-center').getByText('로그인 성공',{exact:true}).count(),0,'로그인 알림이 터미널 기록에 섞였습니다.')
  await page.waitForFunction(()=>document.querySelector('.xterm-screen')?.textContent.includes('fixture-user@preview:'))
  await page.keyboard.type('whoami');await page.keyboard.press('Enter')
  await page.waitForFunction(()=>document.querySelector('.xterm-screen')?.textContent.includes('fixture-user'))
  await terminal.getByRole('button',{name:'파일 전송',exact:true}).click()
  const files=page.getByRole('region',{name:'파일 전송 · 123456789',exact:true})
  await page.waitForFunction(()=>document.querySelector('.files-location input')?.value==='/home/fixture-user')
  const pathInput=files.getByRole('textbox',{name:'현재 경로',exact:true})
  const idle=()=>page.waitForFunction(()=>!document.querySelector('.files-location input')?.disabled)
  const go=async path=>{await idle();await pathInput.fill(path);await files.getByRole('button',{name:'경로 이동',exact:true}).click();await idle()}
  await go('/tmp')
  await files.getByRole('button',{name:'새 폴더',exact:true}).click()
  let editor=page.getByRole('dialog',{name:'새 폴더',exact:true})
  const folder='manual-check-'+Date.now()
  await editor.getByRole('textbox',{name:'파일명',exact:true}).fill(folder)
  await editor.getByRole('button',{name:'적용',exact:true}).click();await editor.waitFor({state:'hidden'})
  await files.getByRole('button',{name:folder,exact:true}).dblclick()
  await idle()
  const data=Buffer.from('수동 미리보기·실제 로그인·홈 밖 테스트\n'.repeat(120))
  await files.locator('input[type="file"]').setInputFiles({name:'manual.txt',mimeType:'text/plain',buffer:data})
  await page.locator('.notification-summary').getByText('1개 파일을 업로드했습니다.',{exact:true}).waitFor()
  const action=async(op,name)=>{
    await files.getByRole('button',{name:`파일 작업 ${name}`,exact:true}).click()
    await page.getByRole('menuitem',{name:op,exact:true}).click()
    return page.getByRole('dialog',{name:op,exact:true})
  }
  editor=await action('파일 복사','manual.txt')
  await editor.getByRole('textbox',{name:'파일명',exact:true}).fill('copy.txt')
  await editor.getByRole('button',{name:'적용',exact:true}).click();await editor.waitFor({state:'hidden'})
  editor=await action('이름 변경','copy.txt')
  await editor.getByRole('textbox',{name:'파일명',exact:true}).fill('renamed.txt')
  await editor.getByRole('button',{name:'적용',exact:true}).click();await editor.waitFor({state:'hidden'})
  editor=await action('권한 변경','renamed.txt')
  await editor.getByRole('textbox',{name:'권한 (8진수)',exact:true}).fill('000')
  await editor.getByRole('button',{name:'적용',exact:true}).click();await editor.waitFor({state:'hidden'})
  await files.getByRole('button',{name:'다운로드 renamed.txt',exact:true}).click()
  await page.locator('.notification-summary').getByText('지정 OS 계정에 이 파일·폴더 접근 권한이 없습니다.',{exact:true}).waitFor()
  editor=await action('권한 변경','renamed.txt')
  await editor.getByRole('textbox',{name:'권한 (8진수)',exact:true}).fill('640')
  await editor.getByRole('button',{name:'적용',exact:true}).click();await editor.waitFor({state:'hidden'})
  const downloading=page.waitForEvent('download')
  await files.getByRole('button',{name:'다운로드 renamed.txt',exact:true}).click()
  const downloaded=await downloading
  assert.deepEqual(await readFile(await downloaded.path()),data)
  await files.getByRole('button',{name:'파일 패널 닫기',exact:true}).click()
  await terminal.getByRole('button',{name:'파일 전송',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.files-location input')?.value==='/home/fixture-user')
  await go('/tmp/'+folder);await files.getByRole('button',{name:'renamed.txt',exact:true}).waitFor()
  for(const name of ['manual.txt','renamed.txt']){
    await files.getByRole('button',{name:`파일 작업 ${name}`,exact:true}).click()
    await page.getByRole('menuitem',{name:'삭제',exact:true}).click()
    await page.getByRole('dialog',{name:'삭제',exact:true}).getByRole('button',{name:'삭제',exact:true}).click()
    await files.getByRole('button',{name,exact:true}).waitFor({state:'hidden'})
  }
  await go('/tmp')
  await files.getByRole('button',{name:`파일 작업 ${folder}`,exact:true}).click()
  await page.getByRole('menuitem',{name:'삭제',exact:true}).click()
  await page.getByRole('dialog',{name:'삭제',exact:true}).getByRole('button',{name:'삭제',exact:true}).click()
  await files.getByRole('button',{name:folder,exact:true}).waitFor({state:'hidden'})
  await go('/etc');await files.getByText('이 폴더는 읽기 전용입니다.',{exact:true}).waitFor()
  assert.equal(await files.getByRole('button',{name:'업로드',exact:true}).isDisabled(),true)
  await go('/root');await page.locator('.notification-summary').getByText('지정 OS 계정에 이 파일·폴더 접근 권한이 없습니다.',{exact:true}).waitFor()
  await files.getByRole('button',{name:'홈 폴더',exact:true}).click();await page.waitForFunction(()=>document.querySelector('.files-location input')?.value==='/home/fixture-user')
  await terminal.getByRole('button',{name:'터미널 크게 보기',exact:true}).click()
  await page.waitForTimeout(200)
  const layout=await terminal.evaluate(element=>({height:element.getBoundingClientRect().height,viewport:innerHeight,scroll:element.scrollHeight-element.clientHeight,bodyScroll:element.querySelector('.el-dialog__body').scrollHeight-element.querySelector('.el-dialog__body').clientHeight}))
  assert.ok(Math.abs(layout.height-layout.viewport)<2 && layout.scroll<2 && layout.bodyScroll<2,'전체 화면에 바깥쪽 스크롤이 발생했습니다.')
  if(process.env.UI_TEST_SCREENSHOTS)await terminal.screenshot({path:join(process.env.UI_TEST_SCREENSHOTS,'manual-preview-verified.png')})
  await terminal.getByRole('button',{name:'닫기',exact:true}).click()
  await terminal.waitFor({state:'hidden'});await page.locator('.notification-center').waitFor({state:'hidden'})
  await page.getByRole('button',{name:'상세 정보 123456789',exact:true}).click()
  const activity=page.locator('.device-activity-list')
  await activity.getByText('터미널 접속',{exact:true}).first().waitFor()
  await activity.getByText('연결 종료',{exact:true}).first().waitFor()
  assert.ok(await activity.locator('li').count() <= 5, '최근 기록이 5개를 넘었습니다.')
  const historyQuery=async params=>{
    const query=new URLSearchParams({peer_id:String(ready.peer_id),...params})
    const reply=await context.request.get(ready.origin+'/api/admin/terminal/history?'+query,{headers:{'api-token':loginBody.data.token}})
    const value=await reply.json();assert.equal(value.code,0);return value.data
  }
  const firstPage=await historyQuery({page:'1',page_size:'2'})
  assert.equal(firstPage.list.length,2)
  const secondPage=await historyQuery({page:'2',page_size:'2',before_id:String(firstPage.before_id)})
  assert.equal(secondPage.total,firstPage.total)
  assert.ok(secondPage.list.every(row=>!firstPage.list.some(first=>first.id===row.id)), '실제 이력 API 페이지 중복')
  const all=await historyQuery({page:'1',page_size:'50'})
  for(const resource of ['web_terminal','web_files']){
    assert.ok(all.list.some(row=>row.resource===resource&&row.result==='connected'), '실제 암호화 연결 성공 기록 누락')
  }
  await details.getByRole('button',{name:'상세보기',exact:true}).click()
  const historyDialog=page.getByRole('dialog',{name:'접속 기록',exact:true})
  await historyDialog.getByText('연결 중',{exact:true}).first().waitFor()
  if(process.env.UI_TEST_SCREENSHOTS)await historyDialog.screenshot({path:join(process.env.UI_TEST_SCREENSHOTS,'manual-history-verified.png')})
  await page.keyboard.press('Escape');await historyDialog.waitFor({state:'hidden'})
  assert.deepEqual(errors,[])
  assert.deepEqual([...new Set(missing)],[],'테스트 화면에 누락된 API가 있습니다.')
  console.log('PASS: 전용 계정 실제 로그인·암호화 연결, 홈 밖 모의 파일 관리·SHA256·권한 변경/거부·읽기 전용·재연결 보존·정리')
}catch(error){
  console.log('누락 경로:',[...new Set(missing)])
  console.log('미리보기 진단:',await page.locator('body').innerText())
  throw error
}finally{await context.close();await browser.close()}
